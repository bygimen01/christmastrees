export function getCategoryLabel(category: string, locale: Locale) {
  return categoryTranslations[category]?.[locale] ?? category;
}

export function getTypeLabel(type: string, locale: Locale) {
  return typeTranslations[type]?.[locale] ?? type;
}

export function getAttrLabel(attr: string, locale: Locale) {
  return attrTranslations[attr]?.[locale] ?? attr;
}

export function getProductTitle(title: string, locale: Locale) {
  if (locale === "ru") {
    return title;
  }

  return `${title.replace(/^Ель\s+/i, "").trim()} шыршасы`;
}

export function getProductSummary(title: string, type: string, heights: string[], locale: Locale) {
  const firstHeight = heights[0];
  const lastHeight = heights[heights.length - 1];

  if (locale === "ru") {
    return `${title} с типом кроны «${getTypeLabel(type, locale)}», доступна в высотах ${firstHeight}–${lastHeight} см.`;
  }

  return `${getProductTitle(title, locale)}: ${getTypeLabel(type, locale).toLowerCase()} модель, қолжетімді биіктіктері ${firstHeight}–${lastHeight} см.`;
}
